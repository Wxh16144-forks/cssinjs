import type { Nonce } from '../util';

export type EngineType = 'auto' | 'legacy' | 'sheet';

/**
 * A group of CSS rules registered as one unit.
 *
 * The group is the smallest unit the DOM backend can delete, which maps to a
 * single `<style>` element in the legacy backend and a range of rules in the
 * virtual sheet backend.
 */
export interface InjectParams {
  /** Unique id of this style group, also used as the style hash. */
  key: string;
  /** Normalized CSS text of the whole group. */
  css: string;
  /** Insert order inside the same container. Lower comes first. */
  priority?: number;
  /** `true` prepends the group, `'queue'` prepends after same-priority groups. */
  prepend?: boolean | 'queue';
  /** CSP nonce of the style element. */
  nonce?: Nonce;
  /** Token key, allows removing all groups generated by one token. */
  tokenKey?: string;
  /** Debug only, records the cache path on the element. */
  cachePath?: string;
  /** Where the style should be injected. */
  container?: Element | ShadowRoot;
}

export interface RemoveParams {
  container?: Element | ShadowRoot;
}

/**
 * Minimal handle of an injected group.
 *
 * Legacy backend returns the `<style>` element; the virtual sheet backend
 * returns a detached node kept only as a marker.
 */
export interface StyleHandle {
  setAttribute: (name: string, value: string) => void;
}

export interface StyleEngine {
  readonly type: EngineType;
  /** Inject or update a group. Returns `null` when nothing is rendered. */
  inject: (params: InjectParams) => StyleHandle | null;
  /** Remove a group. */
  remove: (key: string, params?: RemoveParams) => void;
  /** Remove every group generated by the same token key. */
  removeByToken: (tokenKey: string) => void;
}
